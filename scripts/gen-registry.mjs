#!/usr/bin/env node
// Generates src/engine/ops/_registry.ts from the directory listing of src/engine/ops/.
//
// Every `<name>.ts` in that directory that does not start with `_`, is not shared plumbing (`types.ts`, `ext.ts`,
// `chars.ts`) and is not a `<name>.schema.ts` is a mechanic family: its default export is a `FamilyModule`, and the
// barrel folds all of them into the flat lookups the engine consults. The output is deterministic (families sorted
// by file name) and written with LF endings, so `npm run gen:registry` twice produces no diff — lint-ops asserts it.
//
// Usage: node scripts/gen-registry.mjs [--check]   (--check prints the file instead of writing it)
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
export const OPS_DIR = path.join(here, '..', 'src', 'engine', 'ops');
export const OUT_FILE = path.join(OPS_DIR, '_registry.ts');

/** Files in src/engine/ops that are shared plumbing every family may import, not mechanic families. */
export const SHARED = new Set(['types.ts', 'ext.ts', 'chars.ts']);

/** File names in src/engine/ops that are mechanic families (sorted, so the output is stable). */
export function familyFiles(dir = OPS_DIR) {
  return fs.readdirSync(dir)
    .filter(f => f.endsWith('.ts') && !f.startsWith('_') && !f.endsWith('.schema.ts') && !SHARED.has(f))
    .sort();
}

/** A safe TypeScript identifier for a family file ("day-night.ts" -> "family_day_night"). */
function ident(file) { return 'family_' + file.replace(/\.ts$/, '').replace(/[^A-Za-z0-9]/g, '_'); }

export function render(files = familyFiles()) {
  const imports = files.map(f => `import ${ident(f)} from './${f.replace(/\.ts$/, '.js')}';`).join('\n');
  const entries = files.map(f => `  { file: ${JSON.stringify(f)}, mod: ${ident(f)} },`).join('\n');
  return TEMPLATE
    .replace('/*IMPORTS*/', imports ? imports + '\n' : '')
    .replace('/*ENTRIES*/', entries ? '\n' + entries + '\n' : '');
}

const TEMPLATE = `// GENERATED by scripts/gen-registry.mjs — do not edit
// Run \`npm run gen:registry\` after adding, renaming or removing a file in src/engine/ops/.
//
// This barrel is the only thing the core imports from src/engine/ops: every hook point in game.ts, characteristics.ts,
// legal.ts, cost.ts, events.ts, view.ts and agents/defaults.ts reads one of the flat lookups below from a \`default:\`
// branch or a length-guarded fold loop, so a game with no families registered pays one length check per hook site.
//
// Module-evaluation order matters: the core imports this barrel, and this barrel imports the family files, so a family
// may only *type*-import core modules at module scope (see src/engine/ops/_example.ts).
import { BUILTIN_TOKEN_ABILITIES, tokenAbilityIn, type TokenAbilityEntry } from './_tokens.js';
import type {
  CostPart, DamageAssignment, EnterCtx, EventMeta, FamilyModule, Mods, OpCtx, TokenAbility, TriggerCtx, ZoneMoveOverride,
  AltCost, AmountCtx, CardDef, CastZone, Decision, Effect, Game, GameObject, GameState, LegalAction, ManaCost, Player, PlayerAction, PlayerId, StackItem, Step, TargetRef, TargetSpec, Zone,
} from './types.js';

/** One family with the file it came from (runtime registrations report \`(runtime)\`). */
export interface RegistryEntry { file: string; mod: FamilyModule }

/*IMPORTS*/
const GENERATED: RegistryEntry[] = [/*ENTRIES*/];

// ---------------------------------------------------------------- flat lookups (mutated in place by rebuild())
export type EffectOp = (e: never, c: OpCtx) => void | Promise<void>;
export type ConditionOp = (cond: never, s: GameState, src: GameObject) => boolean;
export type AmountOp = (a: never, s: GameState, ctrl: PlayerId, x: number, src?: GameObject, ctx?: AmountCtx) => number;
export type TriggerOp = (ev: never, perm: GameObject, ctx: TriggerCtx, s: GameState, event: string) => boolean;
export type StaticOp = (e: never, src: GameObject, o: GameObject, s: GameState, m: Mods) => void;
export type AsEntersOp = (a: never, o: GameObject, ctx: EnterCtx, g: Game) => Promise<void> | void;
export type StepHook = (g: Game, ap: PlayerId) => Promise<void> | void;
export type SbaHook = (g: Game) => boolean;
export type LegalProvider = (g: Game, p: PlayerId, out: LegalAction[], sorceryTiming: boolean) => void;
export type ActionOp = (g: Game, p: PlayerId, a: never) => Promise<boolean>;
export type DecisionDefault = (s: GameState, me: PlayerId, d: never) => unknown;
export type CanAttackHook = (s: GameState, o: GameObject) => boolean | undefined;
export type CanBlockHook = (s: GameState, blocker: GameObject, attacker: GameObject) => boolean | undefined;
export type BlockCheckHook = (s: GameState, blocker: GameObject, attacker: GameObject) => boolean;
export type BlockFixupHook = (g: Game, attackers: GameObject[], defender: PlayerId) => void;
export type CombatDamageHook = (g: Game, assignments: DamageAssignment[]) => void;
export type TriggerSourceHook = (s: GameState) => GameObject[];
export type RedactHook = (o: GameObject, viewer: PlayerId) => void;
export type RedactPlayerHook = (pl: Player, viewer: PlayerId) => void;
export type RedactStateHook = (s: GameState, viewer: PlayerId) => void;
export type EotCleanupHook = (g: Game, o: GameObject) => void;
export type LeaveHook = (g: Game, o: GameObject, zone: Zone) => void;
export type CastFromHook = (g: Game, p: PlayerId, card: GameObject, from: CastZone) => boolean | undefined;
export type FreeCastHook = (g: Game, p: PlayerId, card: GameObject, from: CastZone) => boolean | undefined;
export type TargetKindHook = (g: Game, controller: PlayerId, source: GameObject, spec: TargetSpec) => TargetRef[];
export type ZoneMoveHook = (g: Game, o: GameObject, zone: Zone, pos: 'top' | 'bottom', reason: string) => ZoneMoveOverride | null;
export type DamageHook = (g: Game, src: GameObject, target: GameObject | PlayerId, n: number, combat: boolean) => number;
export type DrawHook = (g: Game, p: PlayerId) => boolean;
export type CountersHook = (g: Game, o: GameObject, counter: string, delta: number) => number;
export type LifeGainHook = (g: Game, p: PlayerId, n: number) => number;
export type ModeCostHook = (def: CardDef, modes: number[], alt: AltCost | undefined, kicked: boolean) => ManaCost | null;
export type CostModHook = (s: GameState, p: PlayerId, card: GameObject, from: CastZone) => number;
export type RenderOp = (e: never) => string;

export const EFFECT_OPS: Record<string, EffectOp> = {};
export const CONDITIONS: Record<string, ConditionOp> = {};
export const AMOUNTS: Record<string, AmountOp> = {};
export const TRIGGERS: Record<string, TriggerOp> = {};
export const STATICS: Record<string, StaticOp> = {};
export const COST_PARTS: Record<string, CostPart> = {};
export const AS_ENTERS: Record<string, AsEntersOp> = {};
export const REPLACEMENTS: { zoneMove: ZoneMoveHook[]; damage: DamageHook[]; draw: DrawHook[]; counters: CountersHook[]; lifeGain: LifeGainHook[] } = { zoneMove: [], damage: [], draw: [], counters: [], lifeGain: [] };
export const STEP_HOOKS: Record<string, StepHook[]> = {};
export const SBA_HOOKS: SbaHook[] = [];
export const LEGAL_PROVIDERS: LegalProvider[] = [];
export const ACTIONS: Record<string, ActionOp> = {};
export const DECISION_DEFAULTS: Record<string, DecisionDefault> = {};
export const CAN_ATTACK: CanAttackHook[] = [];
export const CAN_BLOCK: CanBlockHook[] = [];
export const BLOCK_CHECKS: BlockCheckHook[] = [];
export const BLOCK_FIXUPS: BlockFixupHook[] = [];
export const COMBAT_DAMAGE_HOOKS: CombatDamageHook[] = [];
export const TRIGGER_SOURCES: TriggerSourceHook[] = [];
export const EVENT_META: Record<string, EventMeta> = {};
export const REDACT_HOOKS: RedactHook[] = [];
export const REDACT_PLAYER_HOOKS: RedactPlayerHook[] = [];
export const REDACT_STATE_HOOKS: RedactStateHook[] = [];
export const EOT_CLEANUP: EotCleanupHook[] = [];
export const RENDERERS: Record<string, RenderOp> = {};
export const LEAVE_HOOKS: LeaveHook[] = [];
export const CAST_FROM_HOOKS: CastFromHook[] = [];
export const FREE_CAST_HOOKS: FreeCastHook[] = [];
export const MODE_COSTS: ModeCostHook[] = [];
export const COST_MODS: CostModHook[] = [];
export const TARGET_KINDS: Record<string, TargetKindHook> = {};
export const TOKEN_ABILITIES: Record<string, TokenAbility> = {};
/** Every registered family, in registration order. */
export const MODULES: FamilyModule[] = [];

/** Per-lookup "is anything registered?" flags: the hot paths test one boolean instead of doing a dictionary miss. */
export const HAS = { effects: false, conditions: false, amounts: false, triggers: false, statics: false, costParts: false, asEnters: false, actions: false, decisions: false, events: false, targetKinds: false, renderers: false };

/** Core \`AbilityCost\` fields; anything else on a cost is looked up in COST_PARTS. */
export const CORE_COST_KEYS: ReadonlySet<string> = new Set<string>([
  'mana', 'tap', 'untap', 'sacrificeSelf', 'sacrifice', 'discard', 'discardSelf', 'energy', 'discardHand', 'payLife',
  'removeCounters', 'exileFromGraveyard', 'exileOtherFromGraveyard', 'exileFromHand', 'returnToHand', 'tapUntappedCreature', 'tapCreaturesTotalPower',
]);

// ---------------------------------------------------------------- (re)build
const RUNTIME: RegistryEntry[] = [];
let TOKEN_ENTRIES: TokenAbilityEntry[] = [];

function clearRecord(r: Record<string, unknown>): void { for (const k in r) delete r[k]; }
function put<T>(target: Record<string, T>, owner: Record<string, string>, key: string, value: T, file: string, what: string): void {
  const prev = owner[key];
  if (prev !== undefined) throw new Error(\`gen:registry — duplicate \${what} "\${key}" registered by both \${prev} and \${file}\`);
  owner[key] = file; target[key] = value;
}

function rebuild(): void {
  for (const r of [EFFECT_OPS, CONDITIONS, AMOUNTS, TRIGGERS, STATICS, COST_PARTS, AS_ENTERS, ACTIONS, DECISION_DEFAULTS, EVENT_META, RENDERERS, TARGET_KINDS, TOKEN_ABILITIES, STEP_HOOKS] as Record<string, unknown>[]) clearRecord(r);
  for (const a of [REPLACEMENTS.zoneMove, REPLACEMENTS.damage, REPLACEMENTS.draw, REPLACEMENTS.counters, REPLACEMENTS.lifeGain, SBA_HOOKS, LEGAL_PROVIDERS, CAN_ATTACK, CAN_BLOCK, BLOCK_CHECKS, BLOCK_FIXUPS, COMBAT_DAMAGE_HOOKS, TRIGGER_SOURCES, REDACT_HOOKS, REDACT_PLAYER_HOOKS, REDACT_STATE_HOOKS, EOT_CLEANUP, LEAVE_HOOKS, CAST_FROM_HOOKS, FREE_CAST_HOOKS, MODE_COSTS, COST_MODS, MODULES] as unknown[][]) a.length = 0;
  for (const k in BUILTIN_TOKEN_ABILITIES) TOKEN_ABILITIES[k] = BUILTIN_TOKEN_ABILITIES[k];
  const owners: Record<string, Record<string, string>> = { effect: {}, condition: {}, amount: {}, trigger: {}, static: {}, 'cost part': {}, 'as-enters': {}, action: {}, decision: {}, event: {}, renderer: {}, 'target kind': {}, 'token ability': Object.fromEntries(Object.keys(BUILTIN_TOKEN_ABILITIES).map(k => [k, '_tokens.ts'])) };
  for (const { file, mod } of [...GENERATED, ...RUNTIME]) {
    MODULES.push(mod);
    if (mod.effects) for (const k in mod.effects) put(EFFECT_OPS, owners.effect, k, mod.effects[k] as EffectOp, file, 'effect');
    if (mod.conditions) for (const k in mod.conditions) put(CONDITIONS, owners.condition, k, mod.conditions[k] as ConditionOp, file, 'condition');
    if (mod.amounts) for (const k in mod.amounts) put(AMOUNTS, owners.amount, k, mod.amounts[k] as AmountOp, file, 'amount');
    if (mod.triggers) for (const k in mod.triggers) put(TRIGGERS, owners.trigger, k, mod.triggers[k] as TriggerOp, file, 'trigger');
    if (mod.statics) for (const k in mod.statics) put(STATICS, owners.static, k, mod.statics[k] as StaticOp, file, 'static');
    if (mod.costParts) for (const k in mod.costParts) put(COST_PARTS, owners['cost part'], k, mod.costParts[k], file, 'cost part');
    if (mod.asEnters) for (const k in mod.asEnters) put(AS_ENTERS, owners['as-enters'], k, mod.asEnters[k] as AsEntersOp, file, 'as-enters kind');
    if (mod.actions) for (const k in mod.actions) put(ACTIONS, owners.action, k, mod.actions[k] as ActionOp, file, 'action');
    if (mod.decisions) for (const k in mod.decisions) put(DECISION_DEFAULTS, owners.decision, k, mod.decisions[k] as DecisionDefault, file, 'decision');
    if (mod.events) for (const k in mod.events) put(EVENT_META, owners.event, k, mod.events[k], file, 'event');
    if (mod.render) for (const k in mod.render) put(RENDERERS, owners.renderer, k, mod.render[k] as RenderOp, file, 'renderer');
    if (mod.targetKinds) for (const k in mod.targetKinds) put(TARGET_KINDS, owners['target kind'], k, mod.targetKinds[k] as TargetKindHook, file, 'target kind');
    if (mod.tokenAbilities) for (const k in mod.tokenAbilities) put(TOKEN_ABILITIES, owners['token ability'], k, mod.tokenAbilities[k], file, 'token ability');
    if (mod.steps) for (const k in mod.steps) (STEP_HOOKS[k] ??= []).push(mod.steps[k as Step] as StepHook);
    const rep = mod.replacements;
    if (rep?.zoneMove) REPLACEMENTS.zoneMove.push(rep.zoneMove as ZoneMoveHook);
    if (rep?.damage) REPLACEMENTS.damage.push(rep.damage as DamageHook);
    if (rep?.draw) REPLACEMENTS.draw.push(rep.draw as DrawHook);
    if (rep?.counters) REPLACEMENTS.counters.push(rep.counters as CountersHook);
    if (rep?.lifeGain) REPLACEMENTS.lifeGain.push(rep.lifeGain as LifeGainHook);
    if (mod.sba) SBA_HOOKS.push(mod.sba);
    if (mod.legalActions) LEGAL_PROVIDERS.push(mod.legalActions);
    const kh = mod.keywordHooks;
    if (kh?.canAttack) CAN_ATTACK.push(kh.canAttack as CanAttackHook);
    if (kh?.canBlock) CAN_BLOCK.push(kh.canBlock as CanBlockHook);
    if (kh?.blockCheck) BLOCK_CHECKS.push(kh.blockCheck as BlockCheckHook);
    if (kh?.blockFixup) BLOCK_FIXUPS.push(kh.blockFixup as BlockFixupHook);
    if (kh?.combatDamage) COMBAT_DAMAGE_HOOKS.push(kh.combatDamage as CombatDamageHook);
    if (mod.triggerSources) TRIGGER_SOURCES.push(mod.triggerSources);
    if (mod.redact) REDACT_HOOKS.push(mod.redact);
    if (mod.redactPlayer) REDACT_PLAYER_HOOKS.push(mod.redactPlayer);
    if (mod.redactState) REDACT_STATE_HOOKS.push(mod.redactState);
    if (mod.cleanupEot) EOT_CLEANUP.push(mod.cleanupEot);
    if (mod.leave) LEAVE_HOOKS.push(mod.leave);
    if (mod.castFrom) CAST_FROM_HOOKS.push(mod.castFrom as CastFromHook);
    if (mod.freeCast) FREE_CAST_HOOKS.push(mod.freeCast as FreeCastHook);
    if (mod.modeCost) MODE_COSTS.push(mod.modeCost as ModeCostHook);
    if (mod.costMod) COST_MODS.push(mod.costMod as CostModHook);
  }
  const any = (r: Record<string, unknown>) => { for (const _k in r) { void _k; return true; } return false; };
  HAS.effects = any(EFFECT_OPS); HAS.conditions = any(CONDITIONS); HAS.amounts = any(AMOUNTS); HAS.triggers = any(TRIGGERS);
  HAS.statics = any(STATICS); HAS.costParts = any(COST_PARTS); HAS.asEnters = any(AS_ENTERS); HAS.actions = any(ACTIONS);
  HAS.decisions = any(DECISION_DEFAULTS); HAS.events = any(EVENT_META); HAS.targetKinds = any(TARGET_KINDS); HAS.renderers = any(RENDERERS);
  TOKEN_ENTRIES = Object.keys(TOKEN_ABILITIES).map(name => ({ name, ab: TOKEN_ABILITIES[name] }));
}
rebuild();

/** Register a family at runtime (tests and probes); the flat lookups are rebuilt. */
export function registerFamily(mod: FamilyModule): void {
  if (MODULES.some(m => m.name === mod.name)) throw new Error(\`registerFamily: "\${mod.name}" is already registered\`);
  RUNTIME.push({ file: \`(runtime) \${mod.name}\`, mod });
  rebuild();
}
/** Remove a runtime-registered family by name. */
export function unregisterFamily(name: string): void {
  const i = RUNTIME.findIndex(r => r.mod.name === name);
  if (i >= 0) { RUNTIME.splice(i, 1); rebuild(); }
}

/** The built-in ability of a predefined token (Treasure/Clue/Food/Spawn and family additions), or undefined. */
export function tokenAbilityOf(o: GameObject): TokenAbility | undefined { return tokenAbilityIn(TOKEN_ENTRIES, o); }

/** fnv-1a over the sorted op / condition / trigger / static / amount names — the cache key for script verification. */
export function registryHash(): string {
  const names = [
    ...Object.keys(EFFECT_OPS).map(k => 'e:' + k), ...Object.keys(CONDITIONS).map(k => 'c:' + k),
    ...Object.keys(TRIGGERS).map(k => 't:' + k), ...Object.keys(STATICS).map(k => 's:' + k), ...Object.keys(AMOUNTS).map(k => 'a:' + k),
  ].sort();
  let h = 0x811c9dc5;
  const s = names.join('|');
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return (h >>> 0).toString(16).padStart(8, '0');
}

export type { CostPart, DamageAssignment, EnterCtx, EventMeta, FamilyModule, Mods, OpCtx, TokenAbility, ZoneMoveOverride };
export type { CastZone, Decision, Effect, Game, GameObject, GameState, LegalAction, Player, PlayerAction, StackItem, TargetSpec };
`;

if (import.meta.url === url.pathToFileURL(process.argv[1] ?? '').href) {
  const text = render();
  if (process.argv.includes('--check')) { process.stdout.write(text); }
  else {
    const before = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (before !== text) { fs.writeFileSync(OUT_FILE, text, 'utf8'); console.log(`gen:registry — wrote ${path.relative(process.cwd(), OUT_FILE)} (${familyFiles().length} families)`); }
    else console.log(`gen:registry — up to date (${familyFiles().length} families)`);
  }
}
