#!/usr/bin/env node
// Builds the mana-symbol and set-icon SVG sprites used by the web app.
//   apps/web/public/mana/sprite.svg   <symbol id="ms-W">…   (one per Scryfall symbology entry with an SVG)
//   apps/web/lib/mana/symbols.ts      SYMBOLS: Record<'{W}', { id, english, colors, mv }>
//   apps/web/public/sets/sprite.svg   <symbol id="set-lea">… (deduped by icon URL; aliases use nested <use>)
//   apps/web/lib/mana/sets.ts         SET_ICON: Record<code, symbolId>
// Polite to Scryfall: UA header, well under 10 req/s (100 ms between SVG downloads).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WEB = path.join(ROOT, 'apps', 'web');
const UA = 'mtg-master-sim/0.1 (local desktop tool)';
const DELAY_MS = 100;

const sleep = (ms) => new Promise(r => setTimeout(r, ms));
let lastRequest = 0;
async function get(url, as = 'text') {
  const wait = lastRequest + DELAY_MS - Date.now();
  if (wait > 0) await sleep(wait);
  lastRequest = Date.now();
  for (let attempt = 0; attempt < 4; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: as === 'json' ? 'application/json' : 'image/svg+xml,*/*' } });
    if (res.status === 429 || res.status >= 500) { await sleep(1000 * (attempt + 1)); continue; }
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    return as === 'json' ? res.json() : res.text();
  }
  throw new Error(`gave up on ${url}`);
}

/** Symbol text → sprite id. `{2/W}` → 2W, `{U/P}` → UP, `{∞}` → INF, `{½}` → HALF, `{T}` → T. */
export function symbolId(sym) {
  const inner = sym.replace(/^\{|\}$/g, '');
  return inner.replace(/∞/g, 'INF').replace(/½/g, 'HALF').replace(/[^A-Za-z0-9]/g, '');
}

/** Take a standalone SVG document and return { viewBox, body } with ids stripped and comments/xml prolog removed. */
function parseSvg(text, { monochrome = false } = {}) {
  const open = text.match(/<svg\b[^>]*>/i);
  if (!open) throw new Error('no <svg>');
  const attrs = open[0];
  let viewBox = attrs.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) {
    const w = parseFloat(attrs.match(/\bwidth="([\d.]+)/)?.[1] ?? '100');
    const h = parseFloat(attrs.match(/\bheight="([\d.]+)/)?.[1] ?? '100');
    viewBox = `0 0 ${w} ${h}`;
  }
  let body = text.slice(open.index + attrs.length).replace(/<\/svg>\s*$/i, '');
  body = body.replace(/<\?xml[^>]*\?>/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/<!DOCTYPE[^>]*>/gi, '');
  body = body.replace(/<title>[\s\S]*?<\/title>/gi, '').replace(/<desc>[\s\S]*?<\/desc>/gi, '').replace(/<metadata>[\s\S]*?<\/metadata>/gi, '');
  body = body.replace(/\s(?:id|xml:space|data-name)="[^"]*"/g, '');
  if (monochrome) {
    // Set icons are single-ink glyphs; let CSS colour them.
    body = body.replace(/\sfill="(?!none)[^"]*"/g, '').replace(/fill:\s*(?!none)[^;"']+;?/g, '');
    body = body.replace(/\sstroke="(?!none)[^"]*"/g, ' stroke="currentColor"');
  }
  body = body.replace(/\s+/g, ' ').trim();
  return { viewBox, body };
}

async function buildMana() {
  console.log('symbology…');
  const json = await get('https://api.scryfall.com/symbology', 'json');
  const entries = (json.data ?? []).filter(e => e.svg_uri);
  const symbols = [];
  const meta = {};
  for (const e of entries) {
    const id = `ms-${symbolId(e.symbol)}`;
    if (meta[e.symbol]) continue;
    try {
      const svg = await get(e.svg_uri);
      const { viewBox, body } = parseSvg(svg);
      symbols.push(`<symbol id="${id}" viewBox="${viewBox}">${body}</symbol>`);
      meta[e.symbol] = { id, english: e.english ?? '', colors: e.colors ?? [], mv: typeof e.mana_value === 'number' ? e.mana_value : (e.cmc ?? 0), hybrid: !!e.hybrid, phyrexian: !!e.phyrexian, mana: !!e.represents_mana, cost: !!e.appears_in_mana_costs };
      process.stdout.write(`\r  ${symbols.length}/${entries.length} ${e.symbol}      `);
    } catch (err) {
      console.warn(`\n  skip ${e.symbol}: ${err.message}`);
    }
  }
  console.log();
  fs.mkdirSync(path.join(WEB, 'public', 'mana'), { recursive: true });
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none">\n${symbols.join('\n')}\n</svg>\n`;
  fs.writeFileSync(path.join(WEB, 'public', 'mana', 'sprite.svg'), sprite);
  fs.mkdirSync(path.join(WEB, 'lib', 'mana'), { recursive: true });
  const ts = `// Generated by scripts/build-mana-sprite.mjs from https://api.scryfall.com/symbology — do not edit.
export interface ManaSymbolInfo { id: string; english: string; colors: string[]; mv: number; hybrid: boolean; phyrexian: boolean; mana: boolean; cost: boolean }
export const SYMBOLS: Record<string, ManaSymbolInfo> = ${JSON.stringify(meta, null, 1)};
export const SYMBOL_COUNT = ${symbols.length};
`;
  fs.writeFileSync(path.join(WEB, 'lib', 'mana', 'symbols.ts'), ts);
  console.log(`mana sprite: ${symbols.length} symbols`);
  return symbols.length;
}

async function buildSets() {
  console.log('sets…');
  const json = await get('https://api.scryfall.com/sets', 'json');
  const sets = (json.data ?? []).filter(s => s.icon_svg_uri);
  const byUrl = new Map(); // bare url → primary code
  for (const s of sets) {
    const bare = s.icon_svg_uri.split('?')[0];
    if (!byUrl.has(bare)) byUrl.set(bare, { url: s.icon_svg_uri, codes: [] });
    byUrl.get(bare).codes.push(s.code);
  }
  const symbols = [];
  const map = {};
  let n = 0;
  for (const [, { url, codes }] of byUrl) {
    // Prefer the code that matches the file name (lea.svg → lea) as the primary id.
    const base = url.split('?')[0].split('/').pop().replace(/\.svg$/, '');
    const primary = codes.includes(base) ? base : codes[0];
    try {
      const svg = await get(url);
      const { viewBox, body } = parseSvg(svg, { monochrome: true });
      symbols.push(`<symbol id="set-${primary}" viewBox="${viewBox}">${body}</symbol>`);
      for (const c of codes) {
        map[c] = `set-${primary}`;
        if (c !== primary) symbols.push(`<symbol id="set-${c}" viewBox="${viewBox}"><use href="#set-${primary}"/></symbol>`);
      }
      n++;
      process.stdout.write(`\r  ${n}/${byUrl.size} icons (${Object.keys(map).length} sets)      `);
    } catch (err) {
      console.warn(`\n  skip ${primary}: ${err.message}`);
    }
  }
  console.log();
  fs.mkdirSync(path.join(WEB, 'public', 'sets'), { recursive: true });
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none">\n${symbols.join('\n')}\n</svg>\n`;
  fs.writeFileSync(path.join(WEB, 'public', 'sets', 'sprite.svg'), sprite);
  const ts = `// Generated by scripts/build-mana-sprite.mjs from https://api.scryfall.com/sets — do not edit.
/** Set code → symbol id inside /sets/sprite.svg (many sets share one icon file). */
export const SET_ICON: Record<string, string> = ${JSON.stringify(map)};
export const SET_ICON_COUNT = ${n};
`;
  fs.writeFileSync(path.join(WEB, 'lib', 'mana', 'sets.ts'), ts);
  console.log(`set sprite: ${n} unique icons for ${Object.keys(map).length} sets`);
  return { icons: n, sets: Object.keys(map).length };
}

const only = process.argv[2];
if (!only || only === 'mana') await buildMana();
if (!only || only === 'sets') await buildSets();
