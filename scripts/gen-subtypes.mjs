#!/usr/bin/env node
// Generates src/cards/subtype-vocab.ts: every subtype the playable pool prints, with the card type it belongs to.
//
// The parser's filter vocabulary must know which words are subtypes ("Zombie", "Plains", "Locus", "Hero") and how
// their plurals read ("Zombies", "Heroes", "Elves", "Plains") — a filter parser that turns any word it does not know
// into a subtype produces filters no object ever matches ("creature you control" → You / Control, "Zombies" → Zomby;
// docs/HANDOFF.md item 22). The vocabulary is a fact about the data set, so it is generated from master.db once and
// committed as source: parse.ts never reads the database.
//
// Usage: node scripts/gen-subtypes.mjs [--check]   (--check prints the file instead of writing it)
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import Database from 'better-sqlite3';
import { PLAYABLE_SQL, splitTypeLine } from './lib.mjs';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const OUT_FILE = path.join(here, '..', 'src', 'cards', 'subtype-vocab.ts');
const DB_FILE = process.env.MTG_DATA_DIR ? path.join(process.env.MTG_DATA_DIR, 'master', 'master.db') : path.join(here, '..', 'data', 'master', 'master.db');

/** The card type a subtype belongs to, from the types of the face that printed it (creature types win on artifact / enchantment creatures). */
function kindOf(types) {
  if (types.includes('Creature') || types.includes('Kindred') || types.includes('Tribal')) return 'Creature';
  for (const t of ['Land', 'Artifact', 'Enchantment', 'Planeswalker', 'Battle']) if (types.includes(t)) return t;
  if (types.includes('Instant') || types.includes('Sorcery')) return 'Spell';
  return null;   // planes, phenomena, schemes, dungeons, stickers: not objects the engine filters
}

/** Multi-word subtypes (and Un-set jokes) whose pieces are not subtypes on their own: "Control Point" is not "Control". */
const MULTIWORD = ['Control Point', 'Infinity Stone', 'Dungeon Master', 'Lady of Proper Etiquette', "The Biggest, Baddest, Nastiest, Scariest Creature You'll Ever See", 'Turtle and/or Elephant', 'Time Lord', "Bolas's Meditation Realm", "Serra's Realm", 'New Phyrexia'];
/** Words that reach the subtype slot of a type line without being one (Un-set type lines). */
const NOT_SUBTYPES = new Set(['You', 'The', 'Of', 'Q', 'Igpay', 'Eaturecray']);

export function collect(dbFile = DB_FILE) {
  const db = new Database(dbFile, { readonly: true });
  const tally = new Map();
  const add = (sub, kind) => {
    if (!kind || !/^[A-Z][A-Za-z'-]+$/.test(sub) || NOT_SUBTYPES.has(sub)) return;   // one word, no "and/or" / "Baddest," / multi-word planes
    const byKind = tally.get(sub) ?? new Map();
    byKind.set(kind, (byKind.get(kind) ?? 0) + 1);
    tally.set(sub, byKind);
  };
  for (const row of db.prepare(`SELECT type_line FROM oracle_cards WHERE ${PLAYABLE_SQL}`).all()) {
    for (const face of row.type_line.split(' // ')) {
      let line = face; for (const mw of MULTIWORD) line = line.replace(mw, '');
      const { types, subtypes } = splitTypeLine(line); const kind = kindOf(types); for (const s of subtypes) add(s, kind);
    }
  }
  db.close();
  const out = {};
  for (const [sub, byKind] of [...tally.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    out[sub] = [...byKind.entries()].sort((a, b) => b[1] - a[1])[0][0];
  }
  return out;
}

export function render(vocab) {
  const lines = [
    '// GENERATED by scripts/gen-subtypes.mjs from data/master/master.db — do not edit by hand (`npm run gen:subtypes`).',
    '// Every subtype the playable pool prints, with the card type it belongs to; src/cards/subtypes.ts reads it.',
    "export type SubtypeKind = 'Creature' | 'Land' | 'Artifact' | 'Enchantment' | 'Planeswalker' | 'Battle' | 'Spell';",
    'export const SUBTYPE_KIND: Readonly<Record<string, SubtypeKind>> = {',
  ];
  let row = ' ';
  for (const [sub, kind] of Object.entries(vocab)) {
    const cell = ` ${/^[A-Za-z]+$/.test(sub) ? sub : JSON.stringify(sub)}: '${kind}',`;
    if (row.length + cell.length > 118) { lines.push(row); row = ' '; }
    row += cell;
  }
  if (row.trim()) lines.push(row);
  lines.push('};', '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
  const text = render(collect());
  if (process.argv.includes('--check')) process.stdout.write(text);
  else { fs.writeFileSync(OUT_FILE, text, 'utf8'); console.log(`wrote ${path.relative(process.cwd(), OUT_FILE)} (${Object.keys(collect()).length} subtypes)`); }
}
